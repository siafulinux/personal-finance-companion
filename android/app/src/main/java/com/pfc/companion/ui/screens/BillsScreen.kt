@Composable
fun BillsScreen(
    onAddBill: () -> Unit,
    onEditBill: (String) -> Unit,
    flash: String? = null,
    onFlashShown: () -> Unit = {},
) {
    val viewModel = rememberScreenViewModel("bills") { BillsViewModel(ServiceLocator.repository) }
    val state by viewModel.state.collectAsStateWithLifecycle()
    val error by viewModel.error.collectAsState()
    var confirmTarget by remember { mutableStateOf<Occurrence?>(null) }

    LifecycleEventEffect(Lifecycle.Event.ON_RESUME) {
        viewModel.refresh()
    }

    Column(modifier = Modifier.fillMaxSize()) {
        Column(modifier = Modifier.padding(horizontal = 20.dp, vertical = 16.dp)) {
            ScreenHeader(
                eyebrow = "Bills",
                title = "Recurring obligations",
                description = "Occurrences are generated by the server from each bill's schedule. Marking one paid updates reserves and Safe-to-Spend.",
            )
        }

        if (flash != null) {
            Card(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 20.dp),
                colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.primaryContainer),
            ) {
                Row(
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(start = 14.dp, end = 4.dp, top = 4.dp, bottom = 4.dp),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically,
                ) {
                    Text(
                        flash,
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onPrimaryContainer,
                        modifier = Modifier.weight(1f),
                    )
                    TextButton(onClick = onFlashShown) { Text("Dismiss") }
                }
            }
        }

        Row(
            modifier = Modifier
                .fillMaxWidth()
                .padding(horizontal = 20.dp, vertical = 10.dp),
            horizontalArrangement = Arrangement.spacedBy(8.dp),
        ) {
            Button(onClick = onAddBill, modifier = Modifier.weight(1f)) {
                Text("Add bill")
            }
        }

        when (val current = state) {
            is UiState.Loading -> LoadingPane("Loading bills")
            is UiState.Failed -> ErrorPane(current.message, onRetry = viewModel::refresh)
            is UiState.Ready -> LazyColumn(
                modifier = Modifier.fillMaxSize(),
                contentPadding = androidx.compose.foundation.layout.PaddingValues(20.dp),
                verticalArrangement = Arrangement.spacedBy(14.dp),
            ) {
                if (error != null) {
                    item {
                        Text(error!!, color = MaterialTheme.colorScheme.error, style = MaterialTheme.typography.bodySmall)
                    }
                }

                if (current.data.suggestions.isNotEmpty()) {
                    item {
                        SectionCard(
                            title = "Payments to confirm",
                            subtitle = "Suggestions from the server — ambiguous matches always wait for you.",
                        ) {
                            current.data.suggestions.forEachIndexed { index, group ->
                                if (index > 0) HorizontalDivider(Modifier.padding(vertical = 10.dp))
                                Text(
                                    group.transactionDescription,
                                    style = MaterialTheme.typography.bodyLarge,
                                    fontWeight = FontWeight.Medium,
                                )
                                Text(
                                    "${formatDate(group.transactionDate)} · ${formatMoney(group.transactionAmount)}" +
                                        (group.transactionMerchant?.let { " · $it" } ?: ""),
                                    style = MaterialTheme.typography.labelSmall,
                                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                                )
                                group.candidates.forEach { candidate ->
                                    SuggestionRow(
                                        candidate = candidate,
                                        onConfirm = { viewModel.confirmMatch(candidate.matchId) },
                                        onReject = { viewModel.rejectMatch(candidate.matchId) },
                                    )
                                }
                            }
                        }
                    }
                }

                item {
                    SectionCard(title = "Upcoming", subtitle = "Next 60 days") {
                        if (current.data.upcoming.isEmpty()) {
                            EmptyMessage("Nothing due soon", "New occurrences appear as bills approach.")
                        } else {
                            current.data.upcoming.forEachIndexed { index, occurrence ->
                                if (index > 0) HorizontalDivider(Modifier.padding(vertical = 10.dp))
                                OccurrenceRow(
                                    occurrence = occurrence,
                                    onMarkPaid = { confirmTarget = occurrence },
                                )
                            }
                        }
                    }
                }

                item {
                    SectionCard(title = "Recurring bills") {
                        if (current.data.bills.isEmpty()) {
                            EmptyMessage("No bills yet", "Add your first recurring bill with the button above.")
                        } else {
                            current.data.bills.forEachIndexed { index, bill ->
                                if (index > 0) HorizontalDivider(Modifier.padding(vertical = 10.dp))
                                BillRow(bill, onEdit = { onEditBill(bill.id) })
                            }
                        }
                    }
                }
            }
        }
    }

    confirmTarget?.let { occurrence ->
        AlertDialog(
            onDismissRequest = { confirmTarget = null },
            title = { Text("Mark this bill paid?") },
            text = {
                Text(
                    "${occurrence.billName ?: "This bill"} · ${formatMoney(occurrence.remainingAmount)} due " +
                        "${formatDate(occurrence.dueDate)}. This records it as paid without creating a transaction."
                )
            },
            confirmButton = {
                TextButton(onClick = {
                    viewModel.markPaid(occurrence.id)
                    confirmTarget = null
                }) { Text("Mark paid") }
            },
            dismissButton = {
                TextButton(onClick = { confirmTarget = null }) { Text("Cancel") }
            },
        )
    }
}

@Composable
private fun OccurrenceRow(occurrence: Occurrence, onMarkPaid: () -> Unit) {
    Row(
        modifier = Modifier.fillMaxWidth(),
        horizontalArrangement = Arrangement.SpaceBetween,
        verticalAlignment = Alignment.CenterVertically,
    ) {
        Column(modifier = Modifier.weight(1f)) {
            Row(verticalAlignment = Alignment.CenterVertically) {
                Text(
                    occurrence.billName ?: "Bill",
                    style = MaterialTheme.typography.bodyLarge,
                    fontWeight = FontWeight.Medium,
                )
                if (occurrence.isOverdue) {
                    Row(modifier = Modifier.padding(start = 6.dp)) { Pill("Overdue", PillTone.Danger) }
                }
                if (occurrence.status == "partial") {
                    Row(modifier = Modifier.padding(start = 6.dp)) { Pill("Partial", PillTone.Warning) }
                }
            }
            Text(
                "${formatDate(occurrence.dueDate)} · ${relativeDueLabel(occurrence.dueDate)}",
                style = MaterialTheme.typography.labelSmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
        }
        Column(horizontalAlignment = Alignment.End) {
            MoneyText(occurrence.remainingAmount, style = MaterialTheme.typography.bodyLarge)
            TextButton(onClick = onMarkPaid) { Text("Mark paid") }
        }
    }
}

@Composable
private fun BillRow(bill: Bill, onEdit: () -> Unit) {
    Row(
        modifier = Modifier.fillMaxWidth(),
        horizontalArrangement = Arrangement.SpaceBetween,
        verticalAlignment = Alignment.CenterVertically,
    ) {
        Column(modifier = Modifier.weight(1f)) {
            Text(
                bill.name,
                style = MaterialTheme.typography.bodyLarge,
                fontWeight = FontWeight.Medium,
            )
            Text(
                listOfNotNull(
                    bill.merchant,
                    bill.frequency.replace('_', ' '),
                    bill.nextDueDate?.let { "next ${formatDate(it)}" },
                    if (!bill.isActive) "paused" else null,
                ).joinToString(" · "),
                style = MaterialTheme.typography.labelSmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
        }
        Column(horizontalAlignment = Alignment.End) {
            MoneyText(bill.expectedAmount, style = MaterialTheme.typography.bodyLarge)
            if (bill.isOverdue) Pill("Overdue", PillTone.Danger)
            TextButton(onClick = onEdit) { Text("Edit") }
        }
    }
}

@Composable
private fun SuggestionRow(
    candidate: MatchCandidate,
    onConfirm: () -> Unit,
    onReject: () -> Unit,
) {
    Column(modifier = Modifier.padding(top = 8.dp)) {
        Row(
            modifier = Modifier.fillMaxWidth(),
            horizontalArrangement = Arrangement.SpaceBetween,
            verticalAlignment = Alignment.CenterVertically,
        ) {
            Column(modifier = Modifier.weight(1f)) {
                Text(
                    "${candidate.billName ?: "Bill"} · due ${formatDate(candidate.dueDate)}",
                    style = MaterialTheme.typography.bodyMedium,
                )
                Text(
                    "${formatMoney(candidate.remaining)} remaining · " +
                        "${(candidate.confidence.toDoubleOrNull()?.times(100))?.toInt() ?: 0}% confidence",
                    style = MaterialTheme.typography.labelSmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
            }
            if (candidate.isAmbiguous) {
                Pill("Ambiguous", PillTone.Warning)
            }
        }
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            TextButton(onClick = onConfirm) { Text("Confirm") }
            TextButton(onClick = onReject) { Text("Not this") }
        }
    }
}
