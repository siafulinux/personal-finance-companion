#!/usr/bin/env python
"""Generate the institution-coverage table from the live provider directories.

Calls the same service the admin "Coverage" button calls
(``provider_selection.coverage``), so the document and the running server cannot
disagree, and writes ``docs/financial-provider-coverage.md``.

What it will not do:

* invent a match — a provider that answers "not listed" is recorded as such;
* treat "listed" as "supported" — the products each directory returns are printed,
  and the selection rule (transactions *and* balances) is stated next to them;
* hide a provider it could not reach — an unconfigured provider and an unreachable
  directory are different rows with different wording.

Usage, from ``backend/`` or from the deployment::

    .venv/bin/python scripts/coverage_report.py
    docker compose exec api python scripts/coverage_report.py
    .venv/bin/python scripts/coverage_report.py --names "USAA,Cash App,Chime"

Exit codes: 0 at least one real provider answered, 2 none did (not configured or
unreachable), so an automated caller can tell "checked and empty" from "not checked".
"""

from __future__ import annotations

import argparse
import sys
from datetime import UTC, datetime
from pathlib import Path

from app.config import PROJECT_ROOT
from app.database.base import SessionLocal
from app.services import provider_config
from app.services.provider_selection import coverage

#: The institutions this project promised to evaluate, plus the borrowing apps that
#: are commonly mistaken for banks. They are evaluated one by one on purpose: an
#: aggregator that reads a checking account does not thereby expose a loan balance.
DEFAULT_NAMES = (
    "USAA",
    "Cash App",
    "Dave",
    "EarnIn",
    "Brigit",
    "Klarna",
    "Afterpay",
    "Affirm",
)

OUTPUT = PROJECT_ROOT / "docs" / "financial-provider-coverage.md"
REAL_PROVIDERS = ("teller", "plaid")


def _cell(row: dict[str, object]) -> str:
    """One provider's answer as a table cell, with its reason when it has none."""
    match = row.get("match")
    if not row.get("available"):
        return f"not available — {row.get('reason') or 'unknown'}"
    if not isinstance(match, dict):
        reason = str(row.get("reason") or "no match")
        # "not listed" is a claim about the institution, and only the institution's own
        # directory can make it. Anything else — an unreachable directory, an auth
        # failure — means this server could not ask, which is a different row.
        return "not listed" if reason == "not listed" else f"not available — {reason}"
    products = ", ".join(match.get("products") or []) or "no products reported"
    flags = []
    if not match.get("transactions"):
        flags.append("no transactions")
    if not match.get("balances"):
        flags.append("no balances")
    suffix = f" — {'; '.join(flags)}" if flags else ""
    return f"**{match.get('name')}** (`{match.get('institution_id')}`): {products}{suffix}"


def _status(report: dict[str, object]) -> tuple[str, list[str]]:
    """Whether this run contains live answers, plus the reasons it may not."""
    reasons: list[str] = []
    live = False
    for institution in report.get("institutions", []):  # type: ignore[union-attr]
        for row in institution.get("providers", []):
            if row.get("provider") not in REAL_PROVIDERS:
                continue
            if row.get("available") and row.get("match") is not None:
                live = True
            elif not row.get("available"):
                reasons.append(f"{row.get('label')}: {row.get('reason')}")
            elif row.get("reason"):
                reasons.append(f"{row.get('label')}: {row.get('reason')}")
    # Deduplicate while keeping order.
    seen: set[str] = set()
    unique = [r for r in reasons if not (r in seen or seen.add(r))]
    return ("live" if live else "not verified"), unique


def render(report: dict[str, object], names: list[str]) -> str:
    state, reasons = _status(report)
    stamp = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "# Institution coverage (generated)",
        "",
        "<!-- Generated by backend/scripts/coverage_report.py; do not edit by hand. -->",
        "",
        f"Generated: {stamp} · institutions: {', '.join(names)} · "
        f"auto-selection: {'on' if report.get('auto_select') else 'off'}",
        "",
    ]
    if state == "live":
        lines += [
            "**Status: live.** At least one provider directory answered, and every row below",
            "records exactly what it returned.",
            "",
        ]
    else:
        lines += [
            "**Status: not verified.** No real provider answered, so no coverage is claimed.",
            "Every row below reflects a missing configuration or an unreachable directory,",
            "not an absence of support at the institution.",
            "",
        ]
        if reasons:
            lines.append("Reasons reported by the server:")
            lines.append("")
            for reason in reasons:
                lines.append(f"- {reason}")
            lines.append("")

    lines += [
        "| Institution | Teller | Plaid | Sandbox |",
        "| --- | --- | --- | --- |",
    ]
    for institution in report.get("institutions", []):  # type: ignore[union-attr]
        by_provider = {row["provider"]: row for row in institution.get("providers", [])}
        lines.append(
            "| {name} | {teller} | {plaid} | {sandbox} |".format(
                name=institution.get("query"),
                teller=_cell(by_provider.get("teller") or {"available": False}),
                plaid=_cell(by_provider.get("plaid") or {"available": False}),
                sandbox=_cell(by_provider.get("sandbox") or {"available": False}),
            )
        )

    lines += [
        "",
        "A row reading `not listed` means the directory answered and does not carry the",
        "institution. A row reading `not available` means this server could not ask. The",
        "selection service additionally requires `transactions` **and** `balances` before it",
        "will use a provider for a real connection, so a listed institution without both is",
        "not offered for syncing.",
        "",
        "Regenerate with (from the repository root):",
        "",
        "```bash",
        "docker compose -f deploy/docker/compose.yaml exec -T api \\",
        "  python scripts/coverage_report.py --out - > docs/financial-provider-coverage.md",
        "```",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--names",
        default=",".join(DEFAULT_NAMES),
        help="Comma-separated institution names to check.",
    )
    parser.add_argument("--out", default=str(OUTPUT), help="Markdown file to write.")
    args = parser.parse_args()

    names = [part.strip() for part in args.names.split(",") if part.strip()]
    db = SessionLocal()
    try:
        states = {state.name: state for state in provider_config.resolve_all(db)}
        report = coverage(db, names)
    finally:
        db.close()

    text = render(report, names)
    if args.out == "-":
        # Inside the API container the repository's docs/ directory does not exist
        # (only app/, scripts/ and migrations/ are copied), so the deployment runs
        # this with --out - and redirects into the checkout.
        print(text)
    else:
        path = Path(args.out)
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path}")
        except OSError as err:
            print(
                f"cannot write {path}: {err}. Use --out - to print the markdown instead.",
                file=sys.stderr,
            )
            return 2

    # Diagnostics never share stdout with `--out -`, or they would land inside the
    # markdown the caller is redirecting into a file.
    log = sys.stderr if args.out == "-" else sys.stdout
    for name in REAL_PROVIDERS:
        state = states.get(name)
        if state is None:
            continue
        origin = state.source if state.configured else "not configured"
        print(f"  {name}: {origin} ({state.environment})", file=log)

    state, reasons = _status(report)
    if state != "live":
        print("coverage is NOT verified; no real provider answered:", file=sys.stderr)
        for reason in reasons:
            print(f"  - {reason}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
